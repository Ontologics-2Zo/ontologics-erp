async function switchProfile(page:Page,profile:string){
 await page.getByLabel('시연 신원',{exact:true}).selectOption(profile);
 const dialog=page.getByRole('dialog',{name:'개발 계정 전환',exact:true});
 // View changes are not unsaved business input.
 await expect(dialog.getByRole('button',{name:'입력 버리고 전환',exact:true})).toHaveCount(0);
 await dialog.getByRole('button',{name:'계정 전환',exact:true}).click();await expect(dialog).not.toBeVisible();
}

